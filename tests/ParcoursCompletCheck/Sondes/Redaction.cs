    public async Task<PreuveSonde> GesteAsync(ContexteSonde c)
    {
        var date = c.Jour.ToString("yyyy-MM-dd", System.Globalization.CultureInfo.InvariantCulture);
        var champs = new Dictionary<string, string>
        {
            ["Ressort"] = "D", ["Contradictoire"] = "O", ["Sens général"] = "FAV", ["Date"] = date, ["Débats publics"] = "1",
        };
        var r = await EcranRedaction.ValiderAsync(c.Client, c.Greffe, Decision, champs);
        if (!r.Fait) return new(false, false, $"Valider la décision {Decision} : {(r.SansEcrivain ? "démonstration" : "refusé")} « {r.Message} »");
        var vue = await EcranRedaction.DecisionsAsync(c.Client, c.Greffe);
        var d = vue.Decisions.FirstOrDefault(x => x.Id == Decision);
        var jour = c.Jour.ToString("dd/MM/yyyy", System.Globalization.CultureInfo.InvariantCulture);
        return d is { Ressort: "Dernier ressort", Contradictoire: "Oui", SensGeneral: "Favorable", DebatsPublics: true, DecisionPublique: false } && d.Date == jour
            ? new(true, true, $"Valider la décision fait (« {r.Message} »), relue par le pont : {d.Ressort}, contradictoire {d.Contradictoire}, {d.SensGeneral}, rendue le {d.Date}, débats publics")
            : new(true, false, $"Valider la décision rendu fait, mais relue {(d is null ? "absente" : $"« {d.Ressort} / {d.Contradictoire} / {d.SensGeneral} / {d.Date} / {d.DebatsPublics} »")}");
    }
